import React, { useState, useEffect } from 'react';
import { X, FileCheck2, AlertCircle, Sparkles, ShieldCheck } from 'lucide-react';
import executionApi from '../../api/execution';

export const DOCUMENT_TYPE_CHOICES = [
  { value: 'RELEASE_TO_SERVICE', label: 'Certificate of Release to Service (CRS)' },
  { value: 'TASK_CHECKLIST', label: 'Maintenance Task Sign-off Checklist' },
  { value: 'INSPECTION_REPORT', label: 'Quality Assurance Inspection Report' },
  { value: 'NDT_REPORT', label: 'Non-Destructive Testing (NDT) Report' },
  { value: 'MODIFICATION_APPROVAL', label: 'Engineering Modification Approval' },
  { value: 'OTHER', label: 'Other Technical Documentation' },
];

export const SIGN_OFF_STATUS_CHOICES = [
  { value: 'DRAFT', label: 'Draft' },
  { value: 'SIGNED', label: 'Signed Off' },
  { value: 'VERIFIED', label: 'Quality Verified' },
  { value: 'REJECTED', label: 'Rejected' },
];

export default function DocumentationModal({
  isOpen,
  onClose,
  execution,
  initialData = null,
  onSuccess,
  currentUserId = null,
}) {
  const isEdit = Boolean(initialData?.id);

  const [formData, setFormData] = useState({
    document_type: 'RELEASE_TO_SERVICE',
    document_number: '',
    title: '',
    issuing_authority: 'FlightFix Quality Assurance / DGCA',
    document_reference: '',
    sign_off_status: 'DRAFT',
    remarks: '',
  });

  const [errors, setErrors] = useState({});
  const [submitting, setSubmitting] = useState(false);
  const [serverError, setServerError] = useState('');

  useEffect(() => {
    if (initialData) {
      setFormData({
        document_type: initialData.document_type || 'RELEASE_TO_SERVICE',
        document_number: initialData.document_number || '',
        title: initialData.title || '',
        issuing_authority: initialData.issuing_authority || 'FlightFix QA',
        document_reference: initialData.document_reference || '',
        sign_off_status: initialData.sign_off_status || 'DRAFT',
        remarks: initialData.remarks || '',
      });
    } else {
      const randomSuffix = Math.floor(1000 + Math.random() * 9000);
      setFormData({
        document_type: 'RELEASE_TO_SERVICE',
        document_number: `CRS-${new Date().getFullYear()}-${randomSuffix}`,
        title: execution?.work_order_number
          ? `Release to Service: ${execution.work_order_number}`
          : 'Certificate of Release to Service',
        issuing_authority: 'FlightFix Quality Assurance / Regulatory Authority',
        document_reference: '',
        sign_off_status: 'DRAFT',
        remarks: 'All maintenance tasks completed in accordance with approved aircraft maintenance manual.',
      });
    }
    setErrors({});
    setServerError('');
  }, [initialData, execution, isOpen]);

  if (!isOpen || !execution) return null;

  const handleChange = (e) => {
    const { name, value } = e.target;
    setFormData((prev) => ({ ...prev, [name]: value }));
    if (errors[name]) {
      setErrors((prev) => ({ ...prev, [name]: null }));
    }
  };

  const autoGenerateDocNumber = () => {
    const prefix = formData.document_type === 'RELEASE_TO_SERVICE' ? 'CRS' : 'DOC';
    const rand = Math.floor(1000 + Math.random() * 9000);
    setFormData((prev) => ({ ...prev, document_number: `${prefix}-${new Date().getFullYear()}-${rand}` }));
  };

  const validate = () => {
    const newErrors = {};
    if (!formData.document_number.trim()) {
      newErrors.document_number = 'Document number is required';
    }
    if (!formData.title.trim()) {
      newErrors.title = 'Title is required';
    }
    if (!formData.issuing_authority.trim()) {
      newErrors.issuing_authority = 'Issuing authority is required';
    }
    setErrors(newErrors);
    return Object.keys(newErrors).length === 0;
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (!validate()) return;

    setSubmitting(true);
    setServerError('');

    const isSigning = formData.sign_off_status === 'SIGNED' || formData.sign_off_status === 'VERIFIED';

    const payload = {
      execution: execution.id,
      document_type: formData.document_type,
      document_number: formData.document_number.trim().toUpperCase(),
      title: formData.title.trim(),
      issuing_authority: formData.issuing_authority.trim(),
      document_reference: formData.document_reference.trim(),
      sign_off_status: formData.sign_off_status,
      remarks: formData.remarks.trim(),
      ...(isSigning && currentUserId
        ? { signed_off_by: currentUserId, signed_off_at: new Date().toISOString() }
        : {}),
    };

    try {
      if (isEdit) {
        await executionApi.updateDocumentationRecord(initialData.id, payload);
      } else {
        await executionApi.createDocumentationRecord(payload);
      }
      onSuccess?.();
      onClose();
    } catch (err) {
      const data = err.response?.data;
      if (data && typeof data === 'object') {
        const fieldErrors = {};
        let generalMsg = '';
        Object.entries(data).forEach(([key, val]) => {
          const message = Array.isArray(val) ? val.join(' ') : String(val);
          if (key in formData) {
            fieldErrors[key] = message;
          } else {
            generalMsg += `${key}: ${message} `;
          }
        });
        setErrors(fieldErrors);
        setServerError(generalMsg || 'Please review highlighted fields.');
      } else {
        setServerError(err.message || 'Failed to save documentation record.');
      }
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto bg-slate-950/70 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="relative bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-lg shadow-2xl overflow-hidden animate-in fade-in zoom-in-95 duration-200">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-900/50">
          <div className="flex items-center space-x-3">
            <div className="w-10 h-10 rounded-xl bg-emerald-500/10 border border-emerald-500/20 flex items-center justify-center text-emerald-400">
              <FileCheck2 className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-base font-semibold text-white">
                {isEdit ? 'Edit Documentation' : 'Issue Maintenance Sign-off / CRS'}
              </h2>
              <p className="text-xs text-slate-400">
                Execution #{execution.id} • Work Order {execution.work_order_number}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-white p-2 rounded-lg hover:bg-slate-800 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Server error */}
        {serverError && (
          <div className="mx-6 mt-4 p-3 rounded-lg bg-rose-500/10 border border-rose-500/20 text-rose-400 text-xs flex items-center space-x-2">
            <AlertCircle className="w-4 h-4 shrink-0" />
            <span>{serverError}</span>
          </div>
        )}

        {/* Form */}
        <form onSubmit={handleSubmit} className="p-6 space-y-4">
          {/* Document Type & Sign-off Status */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-medium text-slate-300 mb-1">
                Document Type <span className="text-rose-400">*</span>
              </label>
              <select
                name="document_type"
                value={formData.document_type}
                onChange={handleChange}
                className="w-full px-3 py-2 bg-slate-800/80 border border-slate-700 rounded-xl text-xs text-white focus:outline-none focus:ring-2 focus:ring-emerald-500"
              >
                {DOCUMENT_TYPE_CHOICES.map((t) => (
                  <option key={t.value} value={t.value}>
                    {t.label}
                  </option>
                ))}
              </select>
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-300 mb-1">
                Sign-off Status <span className="text-rose-400">*</span>
              </label>
              <select
                name="sign_off_status"
                value={formData.sign_off_status}
                onChange={handleChange}
                className="w-full px-3 py-2 bg-slate-800/80 border border-slate-700 rounded-xl text-xs text-white focus:outline-none focus:ring-2 focus:ring-emerald-500"
              >
                {SIGN_OFF_STATUS_CHOICES.map((s) => (
                  <option key={s.value} value={s.value}>
                    {s.label}
                  </option>
                ))}
              </select>
            </div>
          </div>

          {/* Document Number */}
          <div>
            <div className="flex items-center justify-between mb-1">
              <label className="text-xs font-medium text-slate-300">
                Document Number <span className="text-rose-400">*</span>
              </label>
              {!isEdit && (
                <button
                  type="button"
                  onClick={autoGenerateDocNumber}
                  className="text-xs text-emerald-400 hover:text-emerald-300 flex items-center space-x-1"
                >
                  <Sparkles className="w-3 h-3" />
                  <span>Auto Generate</span>
                </button>
              )}
            </div>
            <input
              type="text"
              name="document_number"
              value={formData.document_number}
              onChange={handleChange}
              placeholder="e.g. CRS-2026-0042"
              className={`w-full px-3 py-2 bg-slate-800/80 border rounded-xl text-xs text-white uppercase placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-emerald-500 ${
                errors.document_number ? 'border-rose-500' : 'border-slate-700'
              }`}
            />
            {errors.document_number && <p className="text-xs text-rose-400 mt-1">{errors.document_number}</p>}
          </div>

          {/* Title */}
          <div>
            <label className="block text-xs font-medium text-slate-300 mb-1">
              Title <span className="text-rose-400">*</span>
            </label>
            <input
              type="text"
              name="title"
              value={formData.title}
              onChange={handleChange}
              placeholder="e.g. Certificate of Release to Service - Check A Inspection"
              className={`w-full px-3 py-2 bg-slate-800/80 border rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-emerald-500 ${
                errors.title ? 'border-rose-500' : 'border-slate-700'
              }`}
            />
            {errors.title && <p className="text-xs text-rose-400 mt-1">{errors.title}</p>}
          </div>

          {/* Issuing Authority & Doc Reference */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-medium text-slate-300 mb-1">
                Issuing Authority <span className="text-rose-400">*</span>
              </label>
              <input
                type="text"
                name="issuing_authority"
                value={formData.issuing_authority}
                onChange={handleChange}
                placeholder="e.g. DGCA / FAA / Internal QA"
                className={`w-full px-3 py-2 bg-slate-800/80 border rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-emerald-500 ${
                  errors.issuing_authority ? 'border-rose-500' : 'border-slate-700'
                }`}
              />
              {errors.issuing_authority && <p className="text-xs text-rose-400 mt-1">{errors.issuing_authority}</p>}
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-300 mb-1">
                Document URL / Reference
              </label>
              <input
                type="text"
                name="document_reference"
                value={formData.document_reference}
                onChange={handleChange}
                placeholder="e.g. https://dms.airline.com/crs/0042.pdf"
                className="w-full px-3 py-2 bg-slate-800/80 border border-slate-700 rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-emerald-500"
              />
            </div>
          </div>

          {/* Remarks / Statement */}
          <div>
            <label className="block text-xs font-medium text-slate-300 mb-1">
              Remarks / Compliance Release Statement
            </label>
            <textarea
              name="remarks"
              rows="3"
              value={formData.remarks}
              onChange={handleChange}
              placeholder="Release statement confirming work accomplished in accordance with airworthiness standards..."
              className="w-full px-3 py-2 bg-slate-800/80 border border-slate-700 rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-emerald-500"
            ></textarea>
          </div>

          {/* Actions */}
          <div className="flex items-center justify-end space-x-3 pt-3 border-t border-slate-800">
            <button
              type="button"
              onClick={onClose}
              disabled={submitting}
              className="px-4 py-2 rounded-xl text-xs font-medium text-slate-400 hover:text-white hover:bg-slate-800 transition"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={submitting}
              className="px-5 py-2 bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-medium rounded-xl shadow-lg shadow-emerald-500/25 transition disabled:opacity-50 flex items-center space-x-2"
            >
              {submitting ? (
                <>
                  <div className="w-4 h-4 border-2 border-white/20 border-t-white rounded-full animate-spin"></div>
                  <span>Saving...</span>
                </>
              ) : (
                <span>{isEdit ? 'Update Document' : 'Issue Document'}</span>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
